import type { Asset, Bootstrap, EngineStatus, GenerationRequest, Job, Project, Recipe } from "./server/contracts";

export type Workspace = "image" | "video" | "shots" | "edit" | "sequence" | "workflows" | "library" | "queue" | "settings";
export interface StudioDraft {
  prompt: string;
  negativePrompt: string;
  recipeId: string;
  aspectRatio: string;
  width: number;
  height: number;
  steps: number;
  seed: string;
  duration: number;
  fps: number;
  batchSize: number;
  inputAssetIds: string[];
  parentAssetId: string | null;
}
export interface StudioController {
  data: Bootstrap | null;
  loading: boolean;
  busy: boolean;
  error: string | null;
  notice: string | null;
  workspace: Workspace;
  setWorkspace: (workspace: Workspace) => void;
  projects: Project[];
  project: Project | null;
  selectedProjectId: string | null;
  selectProject: (id: string) => void;
  createProject: (name: string) => Promise<void>;
  renameProject: (id: string, name: string) => Promise<void>;
  assets: Asset[];
  allAssets: Asset[];
  jobs: Job[];
  recipes: Recipe[];
  engine: EngineStatus | null;
  draft: StudioDraft;
  updateDraft: (patch: Partial<StudioDraft>) => void;
  selectRecipe: (id: string) => void;
  selectedAsset: Asset | null;
  setSelectedAsset: (asset: Asset | null) => void;
  importFiles: (files: File[] | FileList) => Promise<void>;
  attachFiles: (files: File[] | FileList) => Promise<Asset[]>;
  attachAssets: (assets: Asset[]) => void;
  openAsset: (asset: Asset) => void;
  reuseJob: (job: Job) => void;
  inlineEdit: (asset: Asset, instruction: string) => Promise<Job | undefined>;
  branchAsset: (asset: Asset) => void;
  recentRecipeIds: string[];
  favoriteRecipeIds: string[];
  toggleFavoriteRecipe: (id: string) => void;
  importBlob: (blob: Blob, name: string, options?: { parentAssetId?: string; projectId?: string | null }) => Promise<Asset | undefined>;
  generate: (overrides?: Partial<GenerationRequest>) => Promise<Job | undefined>;
  cancelJob: (id: string) => Promise<void>;
  retryJob: (job: Job) => Promise<void>;
  starAsset: (asset: Asset) => Promise<void>;
  deleteAsset: (asset: Asset) => Promise<void>;
  useAsset: (asset: Asset, destination?: Workspace) => void;
  downloadAsset: (asset: Asset) => Promise<void>;
  saveDocument: (key: string, document: unknown) => void;
  saveImageDocument: (projectId: string, assetId: string, document: unknown) => void;
  exportProject: () => Promise<void>;
  importProject: (file: File) => Promise<void>;
  refresh: () => Promise<void>;
  connectEngine: (apiKey: string) => Promise<void>;
  disconnectEngine: () => void;
  dismissMessage: () => void;
}
export type { Asset, Bootstrap, EngineStatus, GenerationRequest, Job, Project, Recipe };
